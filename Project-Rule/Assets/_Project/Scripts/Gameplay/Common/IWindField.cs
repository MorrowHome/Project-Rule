using UnityEngine;

namespace RuleGame.Gameplay.Common
{
    /// <summary>
    /// 风场：在一个区域里给**任何进入其中的实体**一个持续的外力。
    /// </summary>
    /// <remarks>
    /// <para><b>为什么需要它</b>：风不是一次性冲量（那是击退），也不是全局常量（那是重力），
    /// 而是**随位置变化的持续外力**。它要有自己的载体，于是有了这个接口。</para>
    ///
    /// <para><b>为什么报「力」而不是「加速度」</b>：这是本接口唯一要紧的设计决定。
    /// 加速度让所有实体飞得一样高，质量就没有意义了；报力、由实体自己除以质量，
    /// 「质量 × 增强 / 削弱 / 反转」这条规则才真正改变**人在风里浮多高**。
    /// 与重力正好互补 —— 重力给的是恒定加速度（与质量无关），风给的是恒定力（与质量有关）。</para>
    ///
    /// <para><b>它是被动探测的</b>：与 <see cref="IMovingSurface"/> 同一个模式。
    /// 风场**不主动推谁**（玩家和敌人都是 Kinematic 刚体，引擎的力对它们无效），
    /// 由实体每个物理帧查一次「我在哪个风场里、这里的力是多少」。
    /// 所以耦合点只有本接口：实体不认识任何具体风场组件。</para>
    /// </remarks>
    public interface IWindField
    {
        /// <summary>
        /// 这个点上的风力（**牛顿**，世界坐标向量）。不在场内时返回 <see cref="Vector2.zero"/>。
        /// </summary>
        /// <remarks>⚠️ 返回的是**力**。调用方要自己除以承受方的质量得到加速度 ——
        /// 这是「质量规则能改变浮空高度」的前提。</remarks>
        Vector2 ForceAt(Vector2 point);

        /// <summary>
        /// 这个点上的**空气阻力系数**（每秒速度衰减率，0 = 无阻力）。不在场内时为 0。
        /// </summary>
        /// <remarks>
        /// <para>它就是风的「耗散」。没有它，风场里的物体会在平衡点附近**永远弹射**：
        /// 从低处进来时被持续加速，带的动能足以冲过平衡点、一路飞出场顶 ——
        /// 实测出场速度 18 m/s，再掉回来重复。有了阻力才会收敛到 <c>F(y) = m·g</c> 那个高度。</para>
        /// <para>物理上就是空气阻力 <c>F = -c·v</c>；实现上按「每秒衰减率」解释，
        /// 与速度无关的绝对量。**各向同性** —— 水平与竖直都收。</para>
        /// </remarks>
        float DragAt(Vector2 point);

        /// <summary>
        /// 这个点上的**竖直阻尼系数**（每秒衰减率，0 = 无）。**只作用于竖直方向的速度**。
        /// 不在场内时为 0。
        /// </summary>
        /// <remarks>
        /// <para>与 <see cref="DragAt"/> 的区别就一条：<see cref="DragAt"/> 是各向同性的空气阻力
        /// （水平 + 竖直都收），本项**只沿承受方的「上」轴**收速度，横向完全不动。</para>
        /// <para>用途：让被风吹起来的人**更快停住**。只有力的平衡 + 各向同性阻力时，竖直方向是欠阻尼的
        /// （阻尼比 ≈ 0.26，实测玩家在平衡高度附近要上下弹好几次）；加一项竖直阻尼就把这笔动能收掉了。</para>
        /// <para>它与 <see cref="DragAt"/> **叠加**，不是替换 —— 想只留竖直阻尼，把空气阻力调成 0 即可。</para>
        /// </remarks>
        float VerticalDampingAt(Vector2 point);
    }
}
